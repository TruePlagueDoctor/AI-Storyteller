export function normalizeSeeds(raw) {
  const clean = (arr) =>
    (Array.isArray(arr) ? arr : String(arr || '').split('\n'))
      .map((s) => String(s).trim())
      .filter(Boolean);
  return {
    quirks: clean(raw?.quirks),
    secrets: clean(raw?.secrets),
  };
}
