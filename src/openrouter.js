// Применить, только если история за это время не поменялась: игрок мог
// перегенерировать ход, обрезать ленту или переключить партию.
export function applySummary(plan, text, currentState) {
  const st = plan.state;
  if (currentState !== st) return false;
  if (st.messages[0] !== plan.first || st.messages[plan.cut - 1] !== plan.last) return false;
  if ((st.summary || '') !== plan.prevSummary) return false;
  if (text) st.summary = text;
  st.messages = st.messages.slice(plan.cut);
  return true;
}

// Синхронный вариант (без фона) — оставлен для совместимости.
export async function summarizeHistory({ state, apiKey, timer = null, force = false }) {
  const plan = planSummary(state, { force });
  if (!plan) return false;
  const text = await computeSummary(plan, apiKey, timer);
  return applySummary(plan, text, state);
}

// Учёт для текста, появившегося вне обычного хода (например, «Договорить»).
export async function syncNarration({ state, apiKey, narration }) {
  const journal = [];
  const timer = [];
  if (state.stateSync === false || !syncWorthwhile(state, narration)) return { status: 'skipped', calls: journal, timing: timer };
  try {
    await syncState(state, apiKey, narration, journal, { timer });
    return { status: 'done', calls: journal, timing: timer };
  } catch (e) {
    return { status: 'failed', error: String(e.message || e).slice(0, 200), calls: journal, timing: timer };
  }
}

// Повторный учёт хода (кнопка «переучесть»): мир уже откачен к состоянию
// до учёта, текст хода — как есть (возможно, исправленный игроком).
export async function resyncNarration({ state, apiKey, narration, model }) {
  const journal = [];
  const used = (model && model.trim()) || toolModelOf(state);
  const timer = [];
  try {
    await syncState(state, apiKey, narration, journal, { model: used, timer });
    return { status: 'done', calls: journal, model: used, resynced: true, timing: timer };
  } catch (e) {
    return { status: 'failed', error: String(e.message || e).slice(0, 200), calls: journal, model: used, resynced: true, timing: timer };
  }
}

// Сверка текста с состоянием после учёта: числовые огрехи чиним сразу,
// смысловые передаём рассказчику замечанием на следующий ход.
export function afterSync(state, narration, rolls = []) {
  const issues = findContradictions(state, narration);
  autoFix(issues);
  const scene = findSceneIssues(state, narration, lastPlayerAction(state), rolls);
  state.correctionNote = correctionNote([...issues, ...scene]) || undefined;
  return issues.map((i) => i.text);
}

export async function runTurn({ state, apiKey, skipSync = false, beforeSync = null }) {
  const narrTimer = [];
  if (skipSync) {
    // OOC/служебный ход: чистое повествование, без инструментов и без прохода учёта.
    const { narration, truncated } = await narrate(state, apiKey, false, { allowDice: false, timer: narrTimer });
    return { narration: narration || '(Рассказчик молчит. Попробуй описать своё действие иначе.)', rolls: [], truncated, timing: { narrate: narrTimer } };
  }
  const journal = [];
  const syncTimer = [];
  const sync = state.stateSync !== false; // по умолчанию включён
  const { narration, rolls, truncated } = await narrate(state, apiKey, !sync, { journal, timer: narrTimer });
  let syncInfo;
  // Снимок мира «после текста, до учёта» — для кнопки «переучесть».
  if (sync && beforeSync) { try { beforeSync(); } catch { /* не критично */ } }
  if (!sync) {
    syncInfo = { status: 'inline', calls: journal }; // однопроходный режим: инструменты вызывал сам рассказчик
  } else if (!syncWorthwhile(state, narration)) {
    syncInfo = { status: 'skipped', calls: [] };
  } else {
    try {
      await syncState(state, apiKey, narration, journal, { timer: syncTimer });
      syncInfo = { status: 'done', calls: journal, model: toolModelOf(state), timing: syncTimer };
    } catch (e) {
      // Сбой учёта не должен рушить ход — история важнее. Но он виден в журнале.
      syncInfo = { status: 'failed', error: String(e.message || e).slice(0, 200), calls: journal, model: toolModelOf(state), timing: syncTimer };
    }
  }
  // Сверяем текст с состоянием: числовые огрехи чиним сразу,
  // смысловые передаём рассказчику замечанием на следующий ход.
  const issues = findContradictions(state, narration);
  const fixed = autoFix(issues);
  const scene = findSceneIssues(state, narration, lastPlayerAction(state), rolls);
  state.correctionNote = correctionNote([...issues, ...scene]) || undefined;

  return {
    narration: narration || '(Рассказчик молчит. Попробуй описать своё действие иначе.)',
    rolls,
    truncated,
    issues: issues.map((i) => i.text),
    fixed,
    sync: syncInfo,
    timing: { narrate: narrTimer },
  };
}

