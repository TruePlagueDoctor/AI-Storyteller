// Повтор запроса из диагностики: то же тело (можно с другой моделью), без откатов —
// чтобы увидеть, как модель отвечает именно на это. Состояние игры не меняется.
export async function replayRequest({ id, model, apiKey }) {
  const { getRequest } = await import('./diag.js');
  const rec = await getRequest(id);
  if (!rec) throw new Error('Запись не найдена.');
  if (!rec.full || !rec.full.request) throw new Error('Полное тело этого запроса уже не хранится — повторить нельзя.');
  const body = { ...rec.full.request, usage: { include: true } };
  if (model && model.trim()) body.model = model.trim();
  const t0 = Date.now();
  const ac = new AbortController();
  const timer = setTimeout(() => ac.abort(), REQUEST_TIMEOUT_MS);
  const base = { purpose: 'повтор: ' + rec.summary.purpose, model: body.model, body, replayOf: id, attempts: [] };
  try {
    const res = await fetch(OPENROUTER_URL, {
      method: 'POST',
      headers: { Authorization: `Bearer ${apiKey}`, 'Content-Type': 'application/json', 'HTTP-Referer': 'http://localhost', 'X-Title': 'AI Storyteller' },
      body: JSON.stringify(body), signal: ac.signal,
    });
    if (!res.ok) {
      const text = await res.text().catch(() => '');
      return recordRequest({ ...base, ms: Date.now() - t0, error: `OpenRouter ${res.status}: ${text.slice(0, 500)}`, httpStatus: res.status, rawError: text.slice(0, 4000) });
    }
    return recordRequest({ ...base, ms: Date.now() - t0, data: await res.json() });
  } catch (err) {
    const msg = err.name === 'AbortError' ? `Модель не ответила за ${Math.round(REQUEST_TIMEOUT_MS / 1000)} с.` : `Не удалось связаться с OpenRouter: ${err.message}`;
    return recordRequest({ ...base, ms: Date.now() - t0, error: msg });
  } finally {
    clearTimeout(timer);
  }
}

// ---- Иллюстрация сцены ----
// Модель учёта работает раскадровщиком: выбирает ОДИН момент фрагмента и
// переводит его в booru-теги. Приметы персонажей берёт из их портретных тегов,
// чтобы на картинках сцены они были похожи на свои портреты.
const PORTRAIT_ONLY = /^(portrait|upper body|looking at viewer|close-up portrait|headshot|simple background|dark moody background|detailed face)$/i;
const nameStem = (n) => String(n || '').toLowerCase().split(/\s+/)[0].slice(0, 5);

function sceneCandidates(ctx) {
  const text = String(ctx.text || '').toLowerCase();
  const mentioned = (name) => { const st = nameStem(name); return st.length >= 3 && text.includes(st); };
  const present = new Set(((ctx.scene && ctx.scene.present) || []).map(nameStem));
  const out = [];
  for (const c of ctx.characters || []) {
    if (!(c.active || (c.present && mentioned(c.name)))) continue;
    out.push({ name: c.name, role: c.active ? 'герой (от его лица рассказ)' : 'герой', race: c.race, appearance: c.appearance, social: c.social, tags: c.portraitTags });
  }
  for (const n of ctx.npcs || []) {
    if (n.archived) continue;
    if (!(present.has(nameStem(n.name)) || mentioned(n.name))) continue;
    out.push({ name: n.name, role: 'НПС', race: n.race, appearance: n.appearance || n.description, social: n.social, tags: n.portraitTags });
  }
  return out.slice(0, 8).map((c) => ({
    ...c,
    tags: c.tags ? c.tags.split(',').map((t) => t.trim()).filter((t) => t && !PORTRAIT_ONLY.test(t)).join(', ') : '',
  }));
}

