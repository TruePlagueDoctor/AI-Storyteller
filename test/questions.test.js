// Ответы не заканчиваются вечными вопросами и не переспрашивают решённое.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { findQuestionIssues } from '../src/contradictions.js';
import { composeStorySystem } from '../src/narrator.js';
import { makeState } from './helpers.js';

const withHistory = (...narr) => makeState({ messages: narr.flatMap((t) => [{ role: 'user', content: 'ход' }, { role: 'assistant', content: t }]) });

test('переспрашивание решённого — замечание', () => {
  for (const t of ['Ольт хмурится: «Уверен? Обратной дороги не будет».', 'Марта прищуривается. — Ты точно этого хочешь?', '— Не передумал? — спрашивает капитан.', '«Согласен?» — уточняет он ещё раз.']) {
    const st = withHistory(t);
    assert.ok(findQuestionIssues(st, t).some((i) => i.kind === 'reconfirm'), t);
  }
  for (const t of ['— Сколько стоит переправа? — спрашиваешь ты. — Две монеты, — отвечает лодочник.', 'Он уверен, что ты вернёшься. Дверь закрывается.']) {
    assert.ok(!findQuestionIssues(withHistory(t), t).some((i) => i.kind === 'reconfirm'), t);
  }
});

test('два ответа подряд заканчиваются вопросом — замечание, один — ещё нет', () => {
  const q = (s) => `Ольт смотрит на тебя. — ${s}?`;
  const has = (st, t) => findQuestionIssues(st, t).some((i) => i.kind === 'question-endings');
  let st = withHistory('Дверь хлопает.', q('А деньги есть'), q('Кто тебя прислал'));
  assert.ok(has(st, q('Кто тебя прислал')));
  st = withHistory(q('А деньги есть'), 'Дверь хлопает.', q('Кто тебя прислал'));
  assert.ok(!has(st, q('Кто тебя прислал')));
  // Вопрос с авторской ремаркой после него — тоже концовка вопросом.
  const tailed = 'Марта ставит кружку.\n— И кто тебя прислал? — спрашивает она, не поднимая глаз.';
  st = withHistory(q('А деньги есть'), tailed);
  assert.ok(has(st, tailed));
  // Вопрос в середине, а кончается действием — не считается.
  const mid = '— Кто тебя прислал? — спрашивает она. Не дождавшись ответа, Марта уходит за стойку.';
  st = withHistory(q('А деньги есть'), mid);
  assert.ok(!has(st, mid));
});

test('вопрос-приглашение в конце («что скажешь?», «а ты?») — замечание сразу', () => {
  const has = (t) => findQuestionIssues(withHistory('Дверь хлопает.', t), t).some((i) => i.kind === 'question-invite');
  for (const t of [
    'Ольт пожимает плечами. — Ну так что скажешь?',
    'Она улыбается.\n— А ты что думаешь? — спрашивает Рита.',
    '— Я своё сказал. А ты?',
    '«Что будешь делать?» — Марта ждёт.',
    '— Ну что, идём?',
    // Приглашение предпоследним вопросом, за ним ещё один (случай из игры).
    '— Либо сидим и ждём, либо думаем, как пробиться туда за топливом. Что скажешь, Мита? Твой дар хоть что-то подсказывает, или голова всё ещё забита мыслями о бывшем?',
  ]) assert.ok(has(t), t);
  for (const t of [
    '— Кто тебя прислал?',
    '— Что скажешь в своё оправдание? — Судья не ждёт ответа и бьёт молотком. Тебя уводят.',
    'Ольт молчит. Потом кивает на дверь.',
  ]) assert.ok(!has(t), t);
});

test('вопрос в конце с закрывающей кавычкой тоже считается', () => {
  const st = withHistory('— Куда? —', '«Кто там?»', '«Зачем?»');
  assert.ok(findQuestionIssues(st, '«Зачем?»').some((i) => i.kind === 'question-endings'));
});

test('правило в промте: описание героя — справка, а не тема для реплик; близкие не пересказывают друг другу известное', () => {
  const p = composeStorySystem(makeState());
  assert.match(p, /Описание и прошлое героя — справка для тебя/);
  assert.match(p, /не объясняют друг другу то, что оба знают/);
});

test('правило концовки в промте: не обязательно вопрос, решённое не переспрашивать', () => {
  const p = composeStorySystem(makeState());
  assert.ok(!/Заканчивай ход не настроением, а точкой, где игроку есть что решить или на что ответить\.\n/.test(p));
  assert.match(p, /не переспрашивай/i);
  assert.match(p, /Вопрос персонажа к герою в самом конце — редкость/);
});
